<?php

declare(strict_types=1);

/*
 * Writes tests/Support/plural-rules.json: the CLDR plural categories of every
 * shipped locale and the category of a fixed set of sample numbers, as PHP's
 * ICU computes them through Formatter::pluralCategory().
 *
 * PluralRulesTest asserts the server against the file and plural.test.ts
 * asserts the browser's Intl.PluralRules against it. Run this after adding a
 * locale to src/Lang, or after an ICU upgrade that changes CLDR data, then
 * review the diff: a changed sample means the two runtimes may now disagree.
 *
 *   composer plural-rules:build            write the file
 *   composer plural-rules:build -- --check exit 1 if the file is out of date
 */

use StreamEngine\Core\Formatter;
use StreamEngine\Core\TranslationManager;

require __DIR__.'/../vendor/autoload.php';

/** The numbers recorded per locale: boundaries, teens, hundreds, negatives, fractions. */
const SAMPLES = [
    0, 1, 2, 3, 4, 5, 10, 11, 12, 14, 19, 20, 21, 22, 25,
    100, 101, 102, 103, 111, 1000, 1001, 1000000,
    -1, -2, -21, 0.5, 1.5, 2.5,
];

/** Numbers probed to find which categories a locale uses at all. */
function probeNumbers(): array
{
    return [...range(0, 220), 1000, 1000000, 0.1, 0.5, 1.1, 1.5, 2.1, 2.5];
}

$check = in_array('--check', array_slice($argv, 1), true);
$output = dirname(__DIR__).'/tests/Support/plural-rules.json';

$rows = [];
foreach (TranslationManager::availableLocales() as $locale) {
    $formatter = new Formatter(new TranslationManager($locale, 'en'), $locale);

    $used = [];
    foreach (probeNumbers() as $n) {
        $used[$formatter->pluralCategory($n)] = true;
    }
    $categories = array_values(array_filter(
        Formatter::PLURAL_CATEGORIES,
        static fn (string $category): bool => isset($used[$category]),
    ));

    $samples = [];
    foreach (SAMPLES as $n) {
        $samples[(string) $n] = $formatter->pluralCategory($n);
    }

    $rows[] = sprintf(
        "    %s: {\n        \"categories\": %s,\n        \"samples\": %s\n    }",
        json_encode($locale),
        json_encode($categories),
        json_encode($samples),
    );
}

$comment = 'CLDR plural categories asserted against PHP intl (PluralRulesTest) and the browser '
    .'Intl.PluralRules (plural.test.ts). Generated by bin/build-plural-rules.php from ICU '
    .INTL_ICU_VERSION.'; do not edit by hand.';
$json = "{\n    \"_comment\": ".json_encode($comment, JSON_UNESCAPED_SLASHES).",\n".implode(",\n", $rows)."\n}\n";

if ($check) {
    // The ICU version in the comment differs between machines; compare the data only.
    $strip = static fn (string $text): string => (string) preg_replace('/^    "_comment".*\n/m', '', $text);
    $current = is_file($output) ? (string) file_get_contents($output) : '';
    if ($strip($current) !== $strip($json)) {
        fwrite(STDERR, "tests/Support/plural-rules.json is out of date; run composer plural-rules:build.\n");
        exit(1);
    }
    echo "tests/Support/plural-rules.json is up to date.\n";
    exit(0);
}

file_put_contents($output, $json);
echo sprintf("Wrote plural rules for %d locales (ICU %s).\n", count($rows), INTL_ICU_VERSION);
